int main()
{
    ll cnt = 0;
    ll cnt2 = 0;
    for(ll d=1;d*d<9e18;d++){
        ll t = d*d;
        ll s = sqrt(t);
        ll s2 = sqrt(t+1);
        ll s3 = sqrt(t-1);
        if(s*s!=t){// 平方数が平方数でないと判定される
            cnt++;
        }
        if(s2*s2==t+1 || (s3!=0 && s3*s3==t-1)){// 平方数でないものが平方数であると判定される
            cnt2++;
        }
    }
    cout << cnt << ' ' << cnt2 << endl;
}